def _build_from_curriculum(subject: str, title: str, curriculum) -> dict:
    topics = []
    for topic, points, example, essay, questions in curriculum:
        theory = _theory_block(topic, points, example, essay)
        rows = []
        for i, (stem, options, answer, diff) in enumerate(questions, 1):
            correct = options[answer]
            # הסבר צמוד לשאלה — לא תמיד הנקודה הראשונה בשיעור
            point = points[min(i - 1, len(points) - 1)]
            rows.append(
                _q(
                    subject,
                    topic,
                    f"{subject}_{abs(hash(topic)) % 10**6}_{i}",
                    stem,
                    options,
                    answer,
                    f"התשובה הנכונה היא «{correct}». {point}",
                    difficulty=diff,
                    hint=f"חשבו לפי הכלל: {point}",
                )
            )
        if _topic_allows_ohm_drills(topic):
            rows.extend(_ohm_calc_drills(subject, topic))
        topics.append({"topic": topic, "theory_content": theory, "questions": rows})
    return {
        "subject": subject,
        "title": title,
        "study_path": STUDY_PATH,
        "topics": topics,
        "disclaimer": "חומר לימודי באפליקציה. אינו מחליף הכשרה מקצועית/רישוי רשמי.",
    }


def _topic_allows_ohm_drills(topic: str) -> bool:
    t = topic.casefold()
    return any(k in t for k in ("אוהם", "יסודות", "מתח, זרם", "מתח זרם", "התנגדות"))


def _ohm_calc_drills(subject: str, topic: str) -> list[dict]:
    """תרגילי I=V/R — רק בנושאי אוהם/יסודות, לא בכל שיעור."""
    from core.mcq_quality import numeric_near_misses

    out = []
    cases = [
        (12, 4, 3), (24, 6, 4), (5, 10, 0.5), (100, 25, 4), (9, 3, 3),
        (48, 16, 3), (15, 5, 3), (60, 20, 3), (3, 6, 0.5), (230, 115, 2),
        (18, 9, 2), (40, 8, 5), (6, 3, 2), (120, 40, 3), (10, 20, 0.5),
    ]
    for i, (v, r, i_amp) in enumerate(cases):
        if abs(i_amp - 0.5) < 1e-9:
            correct = "0.5A"
        elif abs(i_amp - int(i_amp)) < 1e-9:
            correct = f"{int(i_amp)}A"
        else:
            correct = f"{i_amp}A"
        wrongs = numeric_near_misses(correct, v=float(v), r=float(r), need=5)
        while len(wrongs) < 3:
            wrongs.append(f"{len(wrongs) + 1}.5A")
        out.append(
            _q(
                subject,
                topic,
                f"{subject}_calc_{i}_{abs(hash(topic)) % 9999}",
                f"מעגל {v}V ו־{r}Ω. מה הזרם? (I = V / R)",
                [correct, wrongs[0], wrongs[1], wrongs[2]],
                0,
                f"I = V/R = {v}/{r} = {i_amp}A. טעויות נפוצות: חיבור V+R, היפוך R/V, או הכפלה/חצייה.",
                difficulty="Easy" if i < 4 else "Medium",
                hint="I = V / R — לא V+R ולא היפוך.",
            )
        )
    return out


