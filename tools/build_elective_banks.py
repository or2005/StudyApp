def _clean(text: str) -> str:
    text = unescape(_TAGS.sub("", text or ""))
    text = re.sub(r"\s+", " ", text).strip(" \t\r\n-–—")
    return text


def _theory_block(title: str, points: list[str], example: str, essay: str) -> str:
    body = "\n\n".join(f"{i}. {p}" for i, p in enumerate(points, 1))
    return f"{title}\n\n{body}\n\nדוגמה\n{example}\n\nהסבר\n{essay}"


def _q(
    subject: str,
    topic: str,
    qid: str,
    question: str,
    options: list[str],
    answer: int,
    explanation: str,
    *,
    difficulty: str = "Medium",
    hint: str = "",
    image: str = "",
    tags: list[str] | None = None,
) -> dict:
    from core.mcq_quality import harden_options

    opts = [str(o).strip() for o in options[:4]]
    while len(opts) < 4:
        opts.append("")
    answer = max(0, min(3, int(answer)))
    opts, answer = harden_options(opts, answer, topic=topic, prompt=question)
    # ערבוב דטרמיניסטי כדי שהנכון לא תמיד א׳
    seed = abs(hash(qid)) % (2**31)
    order = list(range(4))
    # xorshift-ish
    s = seed or 1
    for i in range(3, 0, -1):
        s = (1103515245 * s + 12345) & 0x7FFFFFFF
        j = s % (i + 1)
        order[i], order[j] = order[j], order[i]
    shuffled = [opts[i] for i in order]
    new_answer = order.index(answer)
    correct = shuffled[new_answer]
    row = {
        "id": qid,
        "subject": subject,
        "topic": topic,
        "question": question.strip(),
        "options": shuffled,
        "answer": new_answer,
        "correct_answer": correct,
        "explanation": explanation.strip() if explanation.strip() else f"התשובה הנכונה היא «{correct}».",
        "difficulty": difficulty,
        "kind": "normal",
        "tags": tags or [subject, topic, difficulty],
        "hint": hint or f"פסלו מסיחים שקרובים אבל מחליפים יחידה/נוסחה/הגדרה ב«{topic}».",
    }
    if image:
        row["image"] = image
    return row


