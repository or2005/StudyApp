def _chem_mol() -> list:
    rows = []
    for molarmass in (2, 12, 16, 18, 23, 32, 40, 44, 58):
        for k in (1, 2, 3, 4, 5, 6):
            mass = k * molarmass
            rows.append(_q(
                f"מסה {mass} גרם, מסה מולרית {molarmass} ג׳/מול. מספר המולים",
                k,
                [mass, molarmass, k + 1],
                _why(f"n=m/M = {mass}/{molarmass}={k}."),
                "Medium" if k <= 2 else "Hard",
            ))
    return _chunk("מולים, n=m/M", T("כמות חומר", ["מול = מסה חלקי מסה מולרית.", "n=m/M."], "18 גרם מים, M=18 → 1 מול."), rows, ADV, 40)


