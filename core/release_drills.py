def _q(question, correct, wrongs, why, diff="Medium"):
    # מסיחים חייבים להיות שונים מהנכון ומשונים זה מזה
    seen = {str(correct)}
    clean = []
    for w in wrongs:
        s = str(w)
        if s not in seen:
            clean.append(s)
            seen.add(s)
        if len(clean) >= 3:
            break
    pad = 1
    while len(clean) < 3:
        extra = str(pad)
        if extra not in seen:
            clean.append(extra)
            seen.add(extra)
        pad += 1
    return (
        question,
        str(correct),
        clean[:3],
        why + " קראו שוב את השאלה, בדקו יחידות, ופסלו מה שלא מתאים.",
        diff,
        "מה בדיוק נשאל, סכום, הפרש, מכפלה או אחוז?",
    )


def _why(text: str) -> str:
    return text


def packs_for(key: str) -> list:
    return DRILLS.get(key) or []


def _chunk(title: str, theory: str, rows: list, cat: str, size: int = 80) -> list:
    if not rows:
        return []
    out = []
    total = (len(rows) + size - 1) // size
    for i in range(0, len(rows), size):
        part = rows[i : i + size]
        n = i // size + 1
        label = title if total == 1 else f"{title}, חלק {n}"
        out.append((label, theory, part, cat))
    return out


def _math_block() -> list:
    rows_easy, rows_mid, rows_hard = [], [], []
    # אחוזים שלמים
    for n in range(20, 481, 2):
        for p in (10, 20, 25, 50):
            if (n * p) % 100:
                continue
            val = n * p // 100
            rest = n - val
            rows_easy.append(_q(
                f"{p}% מ־{n} שווה",
                val,
                [rest, p, n + val],
                _why(f"({p}/100)×{n} = {val}. לא מחברים {p} ל־{n}."),
                "Easy",
            ))
    # כפל וחילוק
    for a in range(6, 25):
        for b in (2, 3, 4, 5):
            rows_easy.append(_q(
                f"{a} × {b} =",
                a * b,
                [a + b, a * b + b, abs(a - b) or a + 1],
                _why(f"{a} כפול {b} = {a * b}."),
                "Easy",
            ))
            if a % b == 0:
                rows_easy.append(_q(
                    f"{a} ÷ {b} =",
                    a // b,
                    [a * b, a - b, b],
                    _why(f"{a} חלקי {b} = {a // b}."),
                    "Easy",
                ))
    # ממוצע זוגי
    for a in range(4, 40, 2):
        b = a + 6
        avg = (a + b) // 2
        rows_mid.append(_q(
            f"ממוצע {a} ו־{b}",
            avg,
            [a + b, b - a, a],
            _why(f"({a}+{b})/2 = {avg}."),
            "Medium",
        ))
    # דרך־מהירות־זמן
    for v in (30, 40, 50, 60, 80, 90, 100, 120):
        for t in (2, 3, 4):
            d = v * t
            rows_mid.append(_q(
                f"מהירות {v} קמ״ש במשך {t} שעות. הדרך בק״מ",
                d,
                [v + t, v, t * 10],
                _why(f"דרך = {v}×{t} = {d} ק״מ."),
                "Medium",
            ))
    # יחס
    for a, b, total in ((1, 4, 50), (2, 3, 60), (1, 2, 36), (3, 5, 80), (1, 1, 48), (2, 5, 70), (3, 7, 100), (4, 6, 50)):
        parts = a + b
        if total % parts:
            continue
        u = total // parts
        rows_mid.append(_q(
            f"יחס {a}:{b} מסכום {total}. החלק של {a}",
            a * u,
            [b * u, u, total],
            _why(f"{parts} חלקים, חלק={u}, לכן {a}×{u}={a * u}."),
            "Medium",
        ))
    # עלייה ואז ירידה
    for start in (100, 200, 50, 80, 250, 400):
        up = start * 110 // 100
        down = up * 90 // 100
        rows_hard.append(_q(
            f"מחיר {start} עלה 10% ואז ירד 10%. המחיר הסופי",
            down,
            [start, start * 90 // 100, up],
            _why(f"אחרי עלייה {up}, אחרי ירידה {down}, לא חוזרים ל־{start}."),
            "Hard",
        ))
    # איבר חסר בממוצע
    for avg, n, known in ((10, 5, 36), (8, 4, 22), (12, 6, 55), (20, 5, 84), (15, 4, 40), (9, 5, 32), (11, 4, 30)):
        missing = avg * n - known
        rows_hard.append(_q(
            f"ממוצע {n} מספרים {avg}. סכום {n - 1} מהם {known}. החסר",
            missing,
            [avg, known // n, abs(missing - avg) or missing + 2],
            _why(f"סכום כולל {avg * n}. החסר {missing}."),
            "Hard",
        ))
    # שארית חילוק, תרגול בסיס
    for a in range(21, 90):
        for b in (3, 4, 5, 6, 7, 8):
            r = a % b
            qot = a // b
            rows_easy.append(_q(
                f"השארית ב־{a} ÷ {b}",
                r,
                [qot, a + b, b],
                _why(f"{a} = {b}×{qot} + {r}, לכן השארית {r}."),
                "Easy",
            ))
    theory_e = T("חשבון בסיס", ["אחוז = חלק ממאה.", "כפל לפני חיבור אם אין סוגריים בבעיה מילולית פשוטה כאן.", "שארית = מה שנשאר אחרי חילוק שלם."], "10% מ־80 = 8. שארית 17÷5 = 2.")
    theory_m = T("דרך וממוצע", ["s=v·t.", "ממוצע = סכום/2 לשני מספרים.", "יחס: מחלקים לסך החלקים."], "60 קמ״ש × 3 שעות = 180 ק״מ.")
    theory_h = T("מלכודות אחוז וממוצע", ["עלייה ואז ירידה באותו אחוז לא מבטלות.", "איבר חסר מהסכום."], "100 → 110 → 99.")
    return (
        _chunk("חשבון בסיס, אחוזים, כפל ושארית", theory_e, rows_easy, EASY)
        + _chunk("דרך, ממוצע ויחס", theory_m, rows_mid, MID)
        + _chunk("אחוזים וממוצע, רמה גבוהה", theory_h, rows_hard, ADV)
    )


def _eng_block() -> list:
    verbs = [
        "cook", "clean", "call", "carry", "climb", "close", "count", "cry", "dance",
        "dream", "dress", "earn", "fill", "finish", "follow", "guess", "happen",
        "hurry", "join", "jump", "kick", "kill", "kiss", "knock", "laugh", "learn",
        "listen", "look", "love", "move", "need", "open", "pass", "pick", "plan",
        "play", "pull", "push", "rain", "reach", "rest", "return", "save", "share",
        "shout", "smile", "start", "stay", "stop", "talk", "thank", "travel", "try",
        "turn", "visit", "wait", "walk", "want", "wash", "watch", "work", "worry",
    ]
    easy, mid, hard = [], [], []
    for v in verbs:
        s = v + ("es" if v.endswith(("s", "x", "ch", "sh")) or v.endswith("o") else "s")
        if v.endswith("y") and v[-2:-1] not in "aeiou":
            s = v[:-1] + "ies"
        ed = v + "ed"
        if v.endswith("e"):
            ed = v + "d"
        elif v.endswith("y") and v[-2:-1] not in "aeiou":
            ed = v[:-1] + "ied"
        ing = v + "ing"
        if v.endswith("e") and v not in {"be", "see"}:
            ing = v[:-1] + "ing"
        easy.append(_q(f"She ___ every day. ({v})", s, [v, ed, ing], _why(f"Present simple he/she/it → {s}."), "Easy"))
        easy.append(_q(f"They ___ yesterday. ({v})", ed, [v, s, ing], _why(f"yesterday → past simple {ed}."), "Easy"))
        mid.append(_q(f"He is ___ now. ({v})", ing, [v, s, ed], _why(f"now → be + {ing}."), "Medium"))
        hard.append(_q(f"She has already ___ . ({v})", ed, [v, s, ing], _why(f"have/has + V3. לרגילים V3={ed}."), "Hard"))
    theory_e = T("Present and past", ["every day → V/Vs.", "yesterday → V-ed."], "She cooks; they cooked.")
    theory_m = T("Continuous", ["now / look! → am/is/are + V-ing."], "He is walking.")
    theory_h = T("Present perfect", ["already / yet / since / for → have + V3."], "She has already cooked.")
    return [
        ("English drills, simple tenses", theory_e, easy, EASY),
        ("English drills, continuous", theory_m, mid, MID),
        ("English drills, present perfect", theory_h, hard, ADV),
    ]


