def _num_force() -> list:
    """פיזיקה: הרבה F=ma ייחודיים."""
    rows = []
    for m in range(1, 16):
        for a in range(1, 9):
            f = m * a
            rows.append(_q(
                f"מסה {m} ק״ג, תאוצה {a} מ׳/ש׳². F=ma בניוטון",
                f,
                [m + a, m * a + 1, a],
                _why(f"F={m}×{a}={f} N."),
                "Medium" if m * a < 40 else "Hard",
            ))
    return _chunk("F=ma, תרגול חישובי", T("החוק השני", ["כוח שווה מסה כפול תאוצה.", "יחידה ניוטון."], "2×3=6 N."), rows, MID, 60)


