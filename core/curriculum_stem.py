def _theory_block(title: str, steps: list[str], example: str) -> str:
    lines = [title, "", "בקצב שלכם. קוראים שורה אחת בכל פעם:", ""]
    for i, step in enumerate(steps, start=1):
        lines.append(f"{i}. {step}")
    lines.extend(["", "דוגמה:", example, "", "אם משהו לא ברור, חוזרים לדוגמה, ורק אז לשאלה."])
    return "\n".join(lines)


