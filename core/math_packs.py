def T(title: str, bullets: list[str], example: str, extra: str = "") -> str:
    lines = [title, ""]
    for item in bullets:
        lines.append(f"• {item}")
    lines += ["", "דוגמה:", example]
    if extra:
        lines += ["", extra]
    return "\n".join(lines)


