# שורה: topic, prompt, answer, explanation, accepted, difficulty, write_guide, hint
Row = tuple


def _pack(subject: str, prefix: str, rows: list[Row]) -> list[dict]:
    items = []
    for i, row in enumerate(rows, start=1):
        topic, prompt, answer, expl = row[:4]
        accepted = row[4] if len(row) > 4 and isinstance(row[4], list) else []
        difficulty = "Easy"
        write_guide = ""
        hint = ""
        extras = [x for x in row[4:] if not isinstance(x, list)]
        if extras:
            difficulty = extras[0] if extras[0] in {"Easy", "Medium", "Hard"} else "Easy"
            write_guide = extras[1] if len(extras) > 1 else ""
            hint = extras[2] if len(extras) > 2 else ""
        items.append(
            make_compose(
                subject, topic, f"compose_{prefix}_{i}",
                prompt, answer, expl, accepted, difficulty, write_guide, hint,
            )
        )
    return items


