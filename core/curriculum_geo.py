def _lesson(title: str, body: str, learned: list[str]) -> str:
    points = "\n".join(f"• {p}" for p in learned)
    return (
        f"{title}\n\n{body}\n\n"
        "דוגמה מהחיים:\n"
        "כשקוראים מפה או חדשות, שואלים: איפה זה, באיזו יבשת, ומה האקלים.\n\n"
        "מה למדנו:\n"
        f"{points}"
    )


