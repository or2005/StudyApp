def _theory(title: str, steps: list[str], example: str) -> str:
    lines = [title, "", "קריאה בקצב איטי. שורה-שורה:", ""]
    for i, step in enumerate(steps, start=1):
        lines.append(f"{i}. {step}")
    lines.extend(["", "דוגמה:", example, "", "אחרי הדוגמה אפשר לעבור לתרגול."])
    return "\n".join(lines)


def _pack(subject: str, title: str, blocks: list[tuple[str, str, list]]) -> dict:
    rng = random.Random(subject)
    topics = []
    for topic, theory, items in blocks:
        qs = []
        for i, row in enumerate(items):
            q, ans, wrong, why = row[:4]
            diff = row[4] if len(row) > 4 else "Easy"
            hint = row[5] if len(row) > 5 else ""
            qs.append(
                make_question(
                    subject, topic, f"{subject}_{topic[:8]}_{i+1}",
                    q, ans, wrong, why, diff, hint=hint, rng=rng,
                )
            )
        topics.append({"topic": topic, "theory_content": theory, "questions": qs})
    return wrap_subject(subject, title, topics)


