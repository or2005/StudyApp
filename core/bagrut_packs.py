def T(title: str, points: list[str], example: str, extra: str = "") -> str:
    lines = [title, "", SOURCE_NOTE, "", "קריאה בקצב איטי:", ""]
    for i, p in enumerate(points, 1):
        lines.append(f"{i}. {p}")
    lines.extend(["", "דוגמה:", example])
    if extra:
        lines.extend(["", extra])
    lines.append("\nאחרי הקריאה, תרגול.")
    return "\n".join(lines)


