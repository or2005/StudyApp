def _q(question, correct, wrongs, why, diff="Medium", hint=""):
    seen = {str(correct)}
    clean = []
    for item in wrongs:
        text = str(item)
        if text not in seen:
            clean.append(text)
            seen.add(text)
        if len(clean) >= 3:
            break
    pad = 1
    while len(clean) < 3:
        extra = f"לא מתאים ({pad})"
        if extra not in seen:
            clean.append(extra)
            seen.add(extra)
        pad += 1
    return (question, str(correct), clean[:3], why, diff, hint)


def _why(lead: str, extra: str = "") -> str:
    body = f"{lead} {extra}".strip()
    return body


def _chunk(title: str, theory: str, rows: list, cat: str, size: int = 24) -> list:
    if not rows:
        return []
    out = []
    total = max(1, (len(rows) + size - 1) // size)
    for i in range(0, len(rows), size):
        part = rows[i : i + size]
        n = i // size + 1
        label = title if total == 1 else f"{title} ({n}/{total})"
        out.append((label, theory, part, cat))
    return out


def _lesson(title, bullets, example, rows, cat):
    return (title, T(title, bullets, example), rows, cat)


